-- Tables of a schema the Data API does not expose, reached through views in
-- public, for the supabase_typegen test that embeds through the members
-- generated for the views in its hostile golden. PostgREST relates the views
-- through the foreign keys of the tables behind them.

create schema restricted;

create table restricted.note (
  id bigint generated by default as identity primary key,
  body text not null,
  team_id bigint not null references public.team (id)
);

create table restricted.note_reply (
  id bigint generated by default as identity primary key,
  body text not null,
  note_id bigint not null references restricted.note (id)
);

create view public.note as select * from restricted.note;

create view public.note_reply as select * from restricted.note_reply;
