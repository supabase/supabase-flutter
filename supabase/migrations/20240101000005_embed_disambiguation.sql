-- Tables joined by more than one relationship and through columns named like
-- the tables they reference, for the supabase_typegen test that embeds them
-- through the members generated for the same tables in its hostile golden.

create table public.team (
  id bigint generated by default as identity primary key,
  name text not null,
  owner_id bigint
);

create table public.profile (
  id bigint generated by default as identity primary key,
  name text not null,
  team bigint references public.team (id)
);

alter table public.team
  add constraint team_owner_id_fkey
  foreign key (owner_id) references public.profile (id);

create table public.badge (
  id bigint generated by default as identity primary key,
  name text not null,
  profile bigint not null references public.profile (id),
  team bigint references public.team (id)
);

-- A junction table: next to badge.team, a second relationship between badge
-- and team.
create table public.team_badge (
  team_id bigint not null references public.team (id),
  badge_id bigint not null references public.badge (id),
  primary key (team_id, badge_id)
);
