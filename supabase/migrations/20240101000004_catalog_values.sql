-- Columns of the built-in types PostgREST serializes in a shape of their own,
-- for the tests that read, write and filter them through typed column tokens.

create table public.catalog_values (
  id bigint generated by default as identity primary key,
  relation oid,
  relations oid[],
  transaction xid8,
  position pg_lsn,
  hardware macaddr,
  hardware_history macaddr8[],
  key_columns int2vector,
  argument_types oidvector,
  host inet,
  allowed_networks cidr[],
  location point,
  axis line,
  edge lseg,
  bounds box,
  route path,
  outline polygon,
  reach circle
);
