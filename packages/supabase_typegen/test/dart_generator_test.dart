import 'dart:convert';
import 'dart:io';

// The package version is internal; the tests read it to check the header.
// ignore: invalid_use_of_internal_member
import 'package:supabase_typegen/src/version.dart';
import 'package:supabase_typegen/supabase_typegen.dart';
import 'package:test/test.dart';

import 'goldens/hostile_fixture.dart';

final _whitespace = RegExp(r'\s+');
final _headerVersion = RegExp(r'supabase_typegen \S+ from');

/// Collapses whitespace so the comparison is stable across formatter
/// versions, and blanks the package version in the header so a release bump
/// does not invalidate the goldens; `tool/regenerate_goldens.dart` refreshes
/// the golden.
String _normalize(String code) => code
    .replaceAll(_whitespace, ' ')
    .replaceFirst(_headerVersion, 'supabase_typegen <version> from')
    .trim();

void main() {
  late DatabaseDescription schema;

  setUpAll(() {
    final document =
        jsonDecode(
              File(
                'test/fixtures/generator_metadata.json',
              ).readAsStringSync(),
            )
            as Map<String, dynamic>;
    schema = parseGeneratorMetadata(document);
  });

  test('matches the golden output', () {
    final golden = File('test/goldens/supabase_schema.dart').readAsStringSync();

    expect(
      _normalize(generateDartCode(schema)),
      _normalize(golden),
      reason:
          'The generator output changed. Regenerate the golden with '
          '`dart run tool/regenerate_goldens.dart` and review the diff.',
    );
  });

  test('matches the hostile golden output', () {
    final golden = File('test/goldens/hostile_schema.dart').readAsStringSync();

    expect(
      _normalize(generateDartCode(hostileSchema)),
      _normalize(golden),
      reason:
          'The generator output changed for the pathological schema. '
          'Regenerate the golden with `dart run tool/regenerate_goldens.dart` '
          'and review the diff; the checked-in golden is what proves the '
          'generated code analyzes cleanly for hostile names.',
    );
  });

  test('split representation clauses carry no trailing comma', () {
    final code = generateDartCode(hostileSchema);

    // The name is long enough that the formatter has to split the clause.
    expect(code, contains('PrivateAchievementItemProgressTblInsert._(\n'));
    // Language versions before 3.13 reject a trailing comma there.
    expect(code, isNot(matches(RegExp(r'_json,\s*\)'))));
  });

  test('range columns parse their literal and render it back', () {
    final code = _normalize(generateDartCode(hostileSchema));
    final compact = code.replaceAll(' ', '');

    expect(
      compact,
      contains(
        "PostgrestColumn<MapRow,PostgresRange<int>>"
        "('pages'",
      ),
    );
    expect(
      compact,
      contains(
        "PostgrestNullableColumn<MapRow,"
        "PostgresRange<DateTime>>('during'",
      ),
    );
    expect(
      compact,
      contains(
        "PostgrestColumn<MapRow,PostgresRange<PostgresDate>>('season'",
      ),
    );
    expect(
      code,
      contains(
        "PostgresRange.parse(_json['season'] as String, PostgresDate.parse)",
      ),
    );
    expect(
      code,
      contains("PostgresRange.parse(_json['pages'] as String, int.parse)"),
    );
    expect(
      compact,
      contains(
        "PostgresRange<num>?getprices=>switch(_json['prices']){null=>null,"
        "finalObjectvalue=>PostgresRange.parse(valueasString,num.parse),};",
      ),
    );
    expect(code, contains("'pages': pages.literal,"));
    expect(code, contains("'season': ?season?.literal,"));
    expect(
      code,
      contains("'shift': shift.render(postgresTimestamp.encode),"),
    );
    expect(
      compact,
      contains(
        "'during':?during?.render("
        "(bound)=>postgresTimestamp.encode(bound.toUtc()),),",
      ),
    );
  });

  test('names objects outside public after their schema and emits the '
      'schema of every table', () {
    final code = generateDartCode(schema);

    expect(code, contains('// Source schemas: inventory, public'));
    expect(
      code,
      startsWith(
        '// Generated by supabase_typegen $version from GeneratorMetadata '
        'version 1.\n// Do not edit by hand.\n',
      ),
    );
    expect(
      code,
      contains('enum InventoryCondition implements PostgresValue {'),
    );
    expect(code, contains('enum Mood implements PostgresValue {'));
    expect(code, contains('extension type const InventoryBooksRow('));
    expect(code, contains('extension type const BooksRow('));
    expect(code, contains('class InventoryStock {'));
    expect(code, contains("/// Typed access to the `inventory.stock` table."));
    expect(code, contains("/// Typed access to the `books` table."));
    final compact = _normalize(code).replaceAll(' ', '');
    expect(
      compact,
      contains(
        "PostgrestTable<InventoryStockRow,InventoryStockInsert,"
        "InventoryStockUpdate>('stock',InventoryStockRow.new,"
        "schema:'inventory'",
      ),
    );
    expect(
      compact,
      contains(
        "PostgrestTable<BooksRow,BooksInsert,BooksUpdate>('books',BooksRow.new,"
        "schema:'public'",
      ),
    );
  });

  test('keys into another schema produce no relation member', () {
    final compact = _normalize(generateDartCode(schema)).replaceAll(' ', '');

    // inventory.stock references inventory.books and public.books; only the
    // key within the schema is embeddable through PostgREST.
    expect(
      compact,
      contains(
        "staticconstbooks=PostgrestToOneRelation<InventoryStockRow,"
        "InventoryBooksRow>('books'",
      ),
    );
    expect(compact, isNot(contains('<InventoryStockRow,BooksRow>')));
    expect(compact, isNot(contains('<BooksRow,InventoryStockRow>')));

    final hostile = _normalize(generateDartCode(hostileSchema));
    expect(hostile, contains('class EvilMultilineSchemaNamePostgrestColumn {'));
    expect(
      hostile,
      isNot(contains('EvilMultilineSchemaNamePostgrestColumnRow>(')),
    );
  });

  test('bytea columns read and write through the bytea codec', () {
    final code = _normalize(generateDartCode(hostileSchema));
    final compact = code.replaceAll(' ', '');

    expect(code, contains("import 'dart:typed_data';"));
    expect(
      compact,
      contains(
        "PostgrestNullableColumn<PostgrestTableRow,Uint8List>('uint8_list',"
        "fromJson:_uint8ListFromJson",
      ),
    );
    expect(
      compact,
      contains(
        "Uint8List?getuint8List=>switch(_json['uint8_list']){null=>null,"
        "finalObjectvalue=>postgresBytea.decode(valueasString),};",
      ),
    );
    expect(
      compact,
      contains(
        "'uint8_list':?switch(uint8List){null=>null,"
        "finalvalue=>postgresBytea.encode(value),},",
      ),
    );
    // A column named like the codec cannot shadow it in the conversions.
    expect(
      compact,
      contains(
        "Uint8ListgetpostgresBytea\$=>"
        "postgresBytea.decode(_json['postgres_bytea']asString);",
      ),
    );
    expect(
      compact,
      contains("'postgres_bytea':postgresBytea.encode(postgresBytea\$),"),
    );
    expect(
      compact,
      contains(
        "List<Uint8List>?getblobs=>(_json['blobs']asList<dynamic>?)"
        "?.map((element)=>postgresBytea.decode(elementasString)).toList();",
      ),
    );
    expect(
      compact,
      contains(
        "'blobs':?blobs?.map((element)=>postgresBytea.encode(element))"
        ".toList(),",
      ),
    );
  });

