    test('a stable function is called read-only unless an argument only '
        'fits in a request body', () {
      FunctionDescription stable(
        String name,
        ValueTypeDescription type,
      ) => FunctionDescription(
        schema: 'public',
        name: name,
        overloads: [
          FunctionOverloadDescription(
            arguments: [
              argument('id'),
              FunctionArgumentDescription(
                name: 'extra',
                type: type,
                hasDefault: true,
              ),
            ],
            result: const FunctionNoResult(),
            isVolatile: false,
          ),
        ],
      );

      final code = _normalize(
        generateDartCode(
          withFunctions([
            stable('with_integers', integer),
            stable(
              'with_json',
              const ValueTypeDescription(
                postgresFormat: 'jsonb',
                typeKind: ColumnTypeKind.json,
              ),
            ),
            stable(
              'with_json_array',
              const ValueTypeDescription(
                postgresFormat: '_jsonb',
                typeKind: ColumnTypeKind.array,
                elementTypeKind: ColumnTypeKind.json,
              ),
            ),
            stable(
              'with_integer_vector',
              const ValueTypeDescription(
                postgresFormat: 'int2vector',
                typeKind: ColumnTypeKind.integerVector,
              ),
            ),
            stable(
              'with_integer_vector_array',
              const ValueTypeDescription(
                postgresFormat: '_int2vector',
                typeKind: ColumnTypeKind.array,
                elementTypeKind: ColumnTypeKind.integerVector,
              ),
            ),
            FunctionDescription(
              schema: 'public',
              name: 'volatile',
              overloads: [
                FunctionOverloadDescription(
                  arguments: [argument('id')],
                  result: const FunctionNoResult(),
                ),
              ],
