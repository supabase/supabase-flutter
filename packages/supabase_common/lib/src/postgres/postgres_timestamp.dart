part of 'postgres_values.dart';

/// Converts between a `timestamp` or `timestamptz` value and the text
/// PostgREST carries it as.
///
/// `infinity` and `-infinity` read as [infinity] and [negativeInfinity], the
/// latest and earliest instant a [DateTime] holds, and those two instants are
/// written back as `infinity` and `-infinity`. Any other value is read with
/// [DateTime.parse] and written in ISO 8601 with its offset from UTC.
///
/// ```dart
/// postgresTimestamp.decode('infinity') == postgresTimestamp.infinity
/// postgresTimestamp.encode(DateTime.utc(2024)) // 2024-01-01T00:00:00.000Z
/// ```
///
/// The shared instance is [postgresTimestamp]. Filter values of type
/// [DateTime] and the rows generated by `supabase_typegen` go through it.
@experimental
final class PostgresTimestampCodec extends Codec<DateTime, String> {
  /// Creates the codec; prefer the shared [postgresTimestamp].
  const PostgresTimestampCodec();

  /// The value `infinity` reads as.
  DateTime get infinity => postgresTimestampInfinity;

  /// The value `-infinity` reads as.
  DateTime get negativeInfinity => postgresTimestampNegativeInfinity;

  @override
  Converter<DateTime, String> get encoder => const _TimestampEncoder();

  @override
  Converter<String, DateTime> get decoder => const _TimestampDecoder();
}

/// The `timestamp` codec, see [PostgresTimestampCodec].
@experimental
const postgresTimestamp = PostgresTimestampCodec();

final class _TimestampEncoder extends Converter<DateTime, String> {
  const _TimestampEncoder();

  @override
  String convert(DateTime input) => postgresTimestampLiteral(input);
}

final class _TimestampDecoder extends Converter<String, DateTime> {
  const _TimestampDecoder();

  @override
  DateTime convert(String input) => switch (input) {
    'infinity' => postgresTimestampInfinity,
    '-infinity' => postgresTimestampNegativeInfinity,
    _ => DateTime.parse(input),
  };
}
